// 草稿属性独立于力学状态；草稿可吸附、选择和编辑，但不形成计算边界。
let constructionMode = false;
const drawingUndoStack = [];
let drawingHistoryDepth = 0;
let drawingDragSnapshot = null;

function drawingSnapshot() {
  return JSON.stringify({ scene, draft, activeTool, constructionMode });
}

function commitDrawingHistory(before) {
  if (before === drawingSnapshot()) return;
  drawingUndoStack.push(before);
  if (drawingUndoStack.length > 100) drawingUndoStack.shift();
  syncDrawingEditControls();
}

function withDrawingHistory(action) {
  if (drawingHistoryDepth) return action();
  const before = drawingSnapshot();
  drawingHistoryDepth++;
  try { return action(); }
  finally {
    drawingHistoryDepth--;
    commitDrawingHistory(before);
  }
}

function undoDrawing() {
  const snapshot = drawingUndoStack.pop();
  if (!snapshot) return;
  const previous = JSON.parse(snapshot);
  closeShapeEditor();
  scene = previous.scene;
  draft = previous.draft;
  activeTool = previous.activeTool;
  constructionMode = previous.constructionMode;
  document.getElementById("constructionMode").checked = constructionMode;
  selected = null;
  hovered = null;
  interaction = null;
  drawingDragSnapshot = null;
  canvas.classList.remove("panning");
  hideRegionMaterialMenu();
  modelName.value = uiText(scene.name);
  toolButtons.forEach((button) => button.classList.toggle("active", button.dataset.tool === activeTool));
  toolName.textContent = TOOL_LABELS[activeTool];
  canvas.classList.toggle("selecting", activeTool === "select");
  canvas.classList.toggle("erasing", activeTool === "eraser");
  updatePanel();
  syncDrawingEditControls();
  render();
  renderCalculationView();
}

function setConstructionMode(value) {
  constructionMode = Boolean(value);
  draft = null;
  document.getElementById("constructionMode").checked = constructionMode;
  render();
}

// 等分只生成内部点，保留原线段；同位置已有节点时直接复用。
function divideSelectedLine(parts) {
  const info = selectedGeometryInfo();
  if (info?.kind !== "curve" || info.object.type !== "line" ||
      !Number.isInteger(parts) || parts < 2 || parts > 5) return [];
  const curve = info.object;
  if (distance(pointOnCurve(curve, 0), pointOnCurve(curve, 1)) <= INTERSECTION_NODE_TOLERANCE) return [];
  const nodes = [];
  for (let i = 1; i < parts; i++) {
    const point = pointOnCurve(curve, i / parts);
    const node = findGeometryNodeNearWorld(point, INTERSECTION_NODE_TOLERANCE) ||
      createGeometryNode(point, { construction: Boolean(curve.construction), select: false, update: false });
    nodes.push(node);
  }
  rebuildDerivedRegions();
  updatePanel();
  render();
  return nodes;
}

function setSelectedConstruction(value) {
  const info = selectedGeometryInfo();
  if (!info) return;
  const object = info.object;
  object.construction = Boolean(value);
  if (info.kind === "geometryNode") {
    // 手动转换的交点成为独立节点，后续交点同步不再覆盖用户的选择。
    object.autoGenerated = false;
    object.autoRole = "";
    object.intersectionCurveIds = [];
  } else {
    for (const id of object.geometryNodeIds) {
      const node = geometryNodeById(id);
      if (!value || !scene.curves.some((curve) => curve.id !== object.id && !curve.construction && curve.geometryNodeIds.includes(id))) {
        node.construction = Boolean(value);
        node.autoGenerated = false;
        node.autoRole = "";
      }
    }
  }
  rebuildDerivedRegions();
  updatePanel();
  render();
}

function syncDrawingEditControls() {
  const undo = document.getElementById("undoDrawing");
  if (undo) undo.disabled = !drawingUndoStack.length;
  const info = selectedGeometryInfo();
  const convert = document.getElementById("convertConstruction");
  if (convert) {
    convert.disabled = !info;
    convert.textContent = info?.object.construction ? "转为真实几何" : "转为草稿";
  }
  const division = document.getElementById("lineDivisionControls");
  if (division) division.hidden = !(info?.kind === "curve" && info.object.type === "line");
}

// 将一次用户命令作为一个撤回步骤；嵌套创建和自动交点更新并入外层命令。
function installDrawingHistory() {
  const wrap = (action) => function (...args) {
    return withDrawingHistory(() => action.apply(this, args));
  };
  createGeometryNode = wrap(createGeometryNode);
  createCurve = wrap(createCurve);
  createRegularShape = wrap(createRegularShape);
  handleCurveClick = wrap(handleCurveClick);
  createPointLoad = wrap(createPointLoad);
  createDistributedLoad = wrap(createDistributedLoad);
  createBodyForceLoad = wrap(createBodyForceLoad);
  deleteObject = wrap(deleteObject);
  clearScene = wrap(clearScene);
  applySelectedGeometryState = wrap(applySelectedGeometryState);
  applySelectedLoadEditor = wrap(applySelectedLoadEditor);
  assignMaterialToRegion = wrap(assignMaterialToRegion);
  setRegionKind = wrap(setRegionKind);
  divideSelectedLine = wrap(divideSelectedLine);
  setSelectedConstruction = wrap(setSelectedConstruction);
  const down = onPointerDown;
  onPointerDown = function (event) {
    const before = drawingSnapshot();
    down(event);
    if (["drag-geometry-node", "drag-control"].includes(interaction?.mode)) drawingDragSnapshot = before;
  };
  const move = onPointerMove;
  onPointerMove = function (event) {
    drawingHistoryDepth++;
    try { move(event); } finally { drawingHistoryDepth--; }
  };
  const up = onPointerUp;
  onPointerUp = function (event) {
    up(event);
    if (drawingDragSnapshot) {
      commitDrawingHistory(drawingDragSnapshot);
      drawingDragSnapshot = null;
    }
  };
}
