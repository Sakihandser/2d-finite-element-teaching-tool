// 几何变化后重建闭合区域，并同步分析节点/单元的区域与材料归属。
function rebuildDerivedRegions(options = {}) {
  if (options.markAnalysisNodePlacementStale !== false && typeof markAnalysisNodePlacementStale === "function") {
    markAnalysisNodePlacementStale("geometryChanged");
  }
  if (options.markAnalysisMeshStale !== false && typeof markAnalysisMeshStale === "function") {
    markAnalysisMeshStale("geometryChanged");
  }
  syncIntersectionGeometryNodes();
  rebuildClosedRegions();
  if(typeof classifyAnalysisNodeBatch==='function')classifyAnalysisNodeBatch(scene.analysisNodes || []);
  else for(const node of scene.analysisNodes || [])classifyAnalysisNode(node);
  classifyAnalysisElements();
}

// 同步边界交点几何节点：相交边界会生成节点，交点消失后清理不再被边界引用的自动节点。
function syncIntersectionGeometryNodes() {
  const intersections = detectCurveIntersections();
  const autoNodes = scene.geometryNodes.filter(isIntersectionGeometryNode);
  const usedAutoNodeIds = new Set();
  const replacementByAutoNodeId = new Map();
  let changed = false;

  for (const intersection of intersections) {
    const point = roundPoint(intersection.point);
    const curveIds = sortedUniqueCurveIds(intersection.curveIds);
    const existingAtPoint = findGeometryNodeNearWorld(point, INTERSECTION_NODE_TOLERANCE);
    const sameCurveAutoNode = autoNodes.find((node) => !usedAutoNodeIds.has(node.id) && intersectionNodeCurveKey(node) === intersection.curveKey);
    const targetNode = existingAtPoint || sameCurveAutoNode;

    if (targetNode) {
      if (sameCurveAutoNode && sameCurveAutoNode !== targetNode) {
        replacementByAutoNodeId.set(sameCurveAutoNode.id, targetNode);
      }
      changed = updateIntersectionGeometryNode(targetNode, point, curveIds) || changed;
    } else {
      createGeometryNode(point, {
        select: false,
        update: false,
        autoGenerated: true,
        autoRole: INTERSECTION_NODE_ROLE,
        construction: curveIds.some((id) => curveById(id)?.construction),
        intersectionCurveIds: curveIds,
        mechanicalState: intersectionHasStaticBoundary(curveIds) ? "static" : "free",
      });
      changed = true;
    }

    const usedNode = targetNode || findGeometryNodeNearWorld(point, INTERSECTION_NODE_TOLERANCE);
    if (isIntersectionGeometryNode(usedNode)) {
      usedAutoNodeIds.add(usedNode.id);
    }
  }

  for (const node of autoNodes) {
    if (usedAutoNodeIds.has(node.id)) continue;
    const replacement = replacementByAutoNodeId.get(node.id);
    if (replacement) {
      redirectPointLoadsToGeometryNode(node, replacement);
      removeGeometryNodeById(node.id);
      changed = true;
      continue;
    }
    if (isGeometryNodeReferencedByCurve(node.id)) {
      // 自动交点节点被用户拿去作为新边界端点后，提升为普通几何节点，避免清理用户新画的拓扑。
      node.autoGenerated = false;
      node.autoRole = "";
      node.intersectionCurveIds = [];
      changed = true;
      continue;
    }
    detachPointLoadsFromGeometryNode(node);
    removeGeometryNodeById(node.id);
    changed = true;
  }

  if (changed) {
    scene.nextIds.geometryNode = maxNumericId(scene.geometryNodes, "G") + 1;
    if (selected?.type === "geometryNode" && !geometryNodeById(selected.id)) {
      selected = null;
    }
  }
  return intersections;
}

// 检测不同几何边界之间的交点，并把同一位置的多条边界交会合并为一个交点。
function detectCurveIntersections() {
  const rawSegments = createRegionRawSegments(true);
  const rawIntersections = [];
  for (let i = 0; i < rawSegments.length; i++) {
    for (let j = i + 1; j < rawSegments.length; j++) {
      const first = rawSegments[i];
      const second = rawSegments[j];
      if (first.curveId === second.curveId) continue;
      if (!segmentBoundsOverlap(first, second)) continue;
      const hit = segmentIntersection(first.start, first.end, second.start, second.end);
      if (!hit || !isFinitePoint(hit.point)) continue;
      rawIntersections.push({
        point: hit.point,
        curveIds: [first.curveId, second.curveId],
      });
    }
  }
  return mergeCurveIntersections(rawIntersections);
}

// 将采样线段产生的重复交点合并，曲线交点落在采样点上时通常会被多个短线段同时命中。
function mergeCurveIntersections(rawIntersections) {
  const merged = [];
  for (const item of rawIntersections) {
    const point = roundPoint(item.point);
    const existing = merged.find((candidate) => distance(candidate.point, point) <= INTERSECTION_NODE_TOLERANCE);
    if (existing) {
      existing.curveIds = sortedUniqueCurveIds([...existing.curveIds, ...item.curveIds]);
      existing.curveKey = intersectionCurveKey(existing.curveIds);
    } else {
      const curveIds = sortedUniqueCurveIds(item.curveIds);
      merged.push({
        point,
        curveIds,
        curveKey: intersectionCurveKey(curveIds),
      });
    }
  }
  return merged.filter((item) => item.curveIds.length >= 2);
}

// 更新一个交点节点的位置和来源；普通节点只在静态边界经过它时同步为静态。
function updateIntersectionGeometryNode(node, point, curveIds) {
  let changed = false;
  const shouldBeStatic = intersectionHasStaticBoundary(curveIds);
  if (isIntersectionGeometryNode(node)) {
    if (node.x !== point.x || node.y !== point.y) {
      node.x = point.x;
      node.y = point.y;
      changed = true;
    }
    const nextKey = intersectionCurveKey(curveIds);
    if (intersectionNodeCurveKey(node) !== nextKey) {
      node.intersectionCurveIds = curveIds;
      changed = true;
    }
    node.autoGenerated = true;
    node.autoRole = INTERSECTION_NODE_ROLE;
    node.construction = curveIds.some((id) => curveById(id)?.construction);
  }
  if (shouldBeStatic && normalizeMechanicalState(node.mechanicalState) !== "static") {
    node.mechanicalState = "static";
    changed = true;
  }
  return changed;
}

// 判断几何节点是否是程序自动生成的边界交点节点。
function isIntersectionGeometryNode(node) {
  return Boolean(node?.autoGenerated && node.autoRole === INTERSECTION_NODE_ROLE);
}

// 在世界坐标中查找离某点足够近的几何节点，用来避免交点处重复生成节点。
function findGeometryNodeNearWorld(point, tolerance) {
  return scene.geometryNodes.find((node) => distance(node, point) <= tolerance) || null;
}

// 判断一个几何节点是否仍被某条边界作为端点引用。
function isGeometryNodeReferencedByCurve(nodeId) {
  return scene.curves.some((curve) => (curve.geometryNodeIds || []).includes(nodeId));
}

// 将旧交点节点上的点载荷迁移到替代节点，避免节点合并时载荷丢失。
function redirectPointLoadsToGeometryNode(oldNode, replacementNode) {
  for (const load of scene.pointLoads || []) {
    if (load.geometryNodeId === oldNode.id) {
      load.geometryNodeId = replacementNode.id;
      load.anchor = {
        x: roundCoord(replacementNode.x),
        y: roundCoord(replacementNode.y),
      };
    }
  }
}

// 自动交点节点被清理时，点载荷改为自由坐标锚点，避免静默删除载荷。
function detachPointLoadsFromGeometryNode(node) {
  for (const load of scene.pointLoads || []) {
    if (load.geometryNodeId === node.id) {
      load.geometryNodeId = null;
      load.anchor = {
        x: roundCoord(node.x),
        y: roundCoord(node.y),
      };
    }
  }
}

// 从场景中删除指定几何节点，只用于内部清理自动交点节点。
function removeGeometryNodeById(nodeId) {
  scene.geometryNodes = scene.geometryNodes.filter((node) => node.id !== nodeId);
}

// 交点涉及的任意边界为静态时，该交点节点也应视为静态几何节点。
function intersectionHasStaticBoundary(curveIds) {
  return curveIds.some((id) => !curveById(id)?.construction && normalizeMechanicalState(curveById(id)?.mechanicalState) === "static");
}

// 曲线 ID 去重排序，保证 C2/C1 和 C1/C2 得到同一个交点来源键。
function sortedUniqueCurveIds(curveIds) {
  return [...new Set((curveIds || []).map(String).filter(Boolean))].sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
}

// 根据曲线 ID 集合得到稳定键。
function intersectionCurveKey(curveIds) {
  return sortedUniqueCurveIds(curveIds).join("|");
}

// 读取自动交点节点保存的曲线来源键。
function intersectionNodeCurveKey(node) {
  return intersectionCurveKey(node?.intersectionCurveIds || []);
}

// 从当前边界曲线自动识别封闭面域；保留同一组边界对应区域的材料填充。
function rebuildClosedRegions() {
  const previousRegions = Array.isArray(scene.regions) ? scene.regions : [];
  const previousBySignature = new Map();
  for (const region of previousRegions) {
    // 用边界签名作为稳定键：几何稍微移动后仍可把材料和区域类型继承到新识别出的区域。
    if (region.boundarySignature) {
      previousBySignature.set(region.boundarySignature, region);
    }
    const legacySignature = legacyBoundarySignature(region.boundaryCurveIds);
    if (legacySignature && !previousBySignature.has(legacySignature)) {
      previousBySignature.set(legacySignature, region);
    }
  }
  const detectedRegions = detectClosedRegions().sort((a, b) => {
    const ax = a.centroid?.x ?? 0;
    const bx = b.centroid?.x ?? 0;
    const ay = a.centroid?.y ?? 0;
    const by = b.centroid?.y ?? 0;
    return ax - bx || ay - by || a.area - b.area;
  });
  const nextRegions = [];
  for (const detected of detectedRegions) {
    const previous = previousBySignature.get(detected.boundarySignature) || previousBySignature.get(detected.legacyBoundarySignature);
    const previousIdAvailable = previous?.id && !nextRegions.some((region) => region.id === previous.id);
    const id = previousIdAvailable ? previous.id : allocateRegionId(nextRegions);
    const regionKind = normalizeRegionKind(previous?.regionKind ?? previous?.kind ?? previous?.type ?? previous?.isAir);
    const region = {
      id,
      name: previous?.name || `结构 ${id}`,
      regionKind,
      isAir: regionKind === REGION_KIND_AIR,
      isStructure: regionKind === REGION_KIND_STRUCTURE,
      boundaryCurveIds: detected.boundaryCurveIds,
      boundarySegments: (detected.boundarySegments || []).map((segment) => ({
        curveId: segment.curveId,
        t0: roundCoord(segment.t0),
        t1: roundCoord(segment.t1),
        start: roundPoint(segment.start),
        end: roundPoint(segment.end),
      })),
      boundarySignature: detected.boundarySignature,
      legacyBoundarySignature: detected.legacyBoundarySignature,
      polygon: detected.polygon.map(roundPoint),
      centroid: roundPoint(detected.centroid),
      area: roundCoord(Math.abs(detected.area)),
      signedArea: roundCoord(detected.area),
      fillColor: previous?.fillColor || regionDefaultColor(id, nextRegions.length),
      materialId: null,
      materialName: "",
      materialColor: "",
      materialProperties: null,
      material: null,
    };
    setRegionMaterialData(region, regionKind === REGION_KIND_AIR ? null : materialSnapshotForRegion(previous));
    nextRegions.push(region);
  }
  scene.regions = nextRegions;
  scene.nextIds.region = maxNumericId(scene.regions, "R") + 1;
}

// 半边遍历：先把曲线离散为短线段，再沿每条有向线段左侧追踪封闭面。
function detectClosedRegions() {
  const graph = buildRegionSegmentGraph();
  const outgoing = new Map();
  const halfEdges = [];
  for (const edge of graph.halfEdges) {
    halfEdges.push(edge);
    if (!outgoing.has(edge.from)) {
      outgoing.set(edge.from, []);
    }
    outgoing.get(edge.from).push(edge);
  }
  for (const edges of outgoing.values()) {
    edges.sort((a, b) => a.angle - b.angle || a.key.localeCompare(b.key));
  }

  const visited = new Set();
  const regions = [];
  for (const edge of halfEdges) {
    if (visited.has(edge.key)) continue;
    const cycle = [];
    let current = edge;
    let guard = 0;
    // 从任意未访问半边出发，持续取“左侧下一边”；若最终回到起点，就得到一个候选闭合面。
    while (current && !visited.has(current.key) && guard < halfEdges.length + 4) {
      visited.add(current.key);
      cycle.push(current);
      current = nextFaceEdge(current, outgoing);
      guard++;
    }
    if (current?.key === edge.key) {
      const region = buildRegionFromCycle(cycle);
      if (region) {
        regions.push(region);
      }
    }
  }
  return regions;
}

// 把所有边界曲线转换为可做平面图追踪的短线段半边。
function buildRegionSegmentGraph() {
  const rawSegments = createRegionRawSegments();
  const splitParameters = rawSegments.map(() => [0, 1]);
  // 两两检测短线段交点，把交点参数加入切分点，保证平面图中的边只在端点相交。
  for (let i = 0; i < rawSegments.length; i++) {
    for (let j = i + 1; j < rawSegments.length; j++) {
      if (!segmentBoundsOverlap(rawSegments[i], rawSegments[j])) continue;
      const hit = segmentIntersection(rawSegments[i].start, rawSegments[i].end, rawSegments[j].start, rawSegments[j].end);
      if (!hit) continue;
      if (hit.t > REGION_INTERSECTION_TOLERANCE && hit.t < 1 - REGION_INTERSECTION_TOLERANCE) {
        splitParameters[i].push(hit.t);
      }
      if (hit.u > REGION_INTERSECTION_TOLERANCE && hit.u < 1 - REGION_INTERSECTION_TOLERANCE) {
        splitParameters[j].push(hit.u);
      }
    }
  }

  const halfEdges = [];
  rawSegments.forEach((segment, index) => {
    const parameters = uniqueSortedParameters(splitParameters[index]);
    // 按交点参数把原始短线段继续切成更小边，再为每条边生成正反两个半边。
    for (let i = 1; i < parameters.length; i++) {
      const t0 = parameters[i - 1];
      const t1 = parameters[i];
      const start = pointOnSegment(segment.start, segment.end, t0);
      const end = pointOnSegment(segment.start, segment.end, t1);
      if (distance(start, end) <= REGION_POINT_MERGE_TOLERANCE) continue;
      const curveT0 = segment.curveT0 + (segment.curveT1 - segment.curveT0) * t0;
      const curveT1 = segment.curveT0 + (segment.curveT1 - segment.curveT0) * t1;
      const edgeIndex = halfEdges.length;
      addRegionHalfEdgePair(halfEdges, {
        id: `${segment.id}:${edgeIndex}`,
        curveId: segment.curveId,
        start,
        end,
        curveT0,
        curveT1,
        curveForward: segment.curveT1 >= segment.curveT0,
      });
    }
  });
  return { halfEdges };
}

// 线段包围盒快速排除：先用矩形重叠过滤，再做较贵的向量交点计算。
function segmentBoundsOverlap(a, b) {
  const margin = REGION_POINT_MERGE_TOLERANCE;
  return !(
    Math.max(a.start.x, a.end.x) + margin < Math.min(b.start.x, b.end.x) ||
    Math.max(b.start.x, b.end.x) + margin < Math.min(a.start.x, a.end.x) ||
    Math.max(a.start.y, a.end.y) + margin < Math.min(b.start.y, b.end.y) ||
    Math.max(b.start.y, b.end.y) + margin < Math.min(a.start.y, a.end.y)
  );
}

// 将每条曲线采样成短线段；二次曲线、三次曲线和圆弧都走同一套面域识别逻辑。
function createRegionRawSegments(includeConstruction = false) {
  const segments = [];
  for (const curve of scene.curves || []) {
    if (curve.construction && !includeConstruction) continue;
    const points = sampleCurve(curve, curve.type === "line" ? 1 : REGION_SAMPLE_COUNT).filter(isFinitePoint);
    if (points.length < 2) continue;
    for (let i = 1; i < points.length; i++) {
      if (distance(points[i - 1], points[i]) <= REGION_POINT_MERGE_TOLERANCE) continue;
      segments.push({
        id: `${curve.id}:${i - 1}`,
        curveId: curve.id,
        start: points[i - 1],
        end: points[i],
        curveT0: (i - 1) / (points.length - 1),
        curveT1: i / (points.length - 1),
      });
    }
  }
  return segments;
}

// 为一条无向短线段创建两个相反方向的半边，后续面追踪依赖 twinKey 在节点处转向。
function addRegionHalfEdgePair(halfEdges, segment) {
  const from = regionPointKey(segment.start);
  const to = regionPointKey(segment.end);
  if (from === to) return;
  const forwardKey = `${segment.id}:forward`;
  const reverseKey = `${segment.id}:reverse`;
  halfEdges.push({
    key: forwardKey,
    twinKey: reverseKey,
    curveId: segment.curveId,
    from,
    to,
    fromPoint: segment.start,
    toPoint: segment.end,
    curveT0: segment.curveT0,
    curveT1: segment.curveT1,
    curveForward: segment.curveForward,
    angle: Math.atan2(segment.end.y - segment.start.y, segment.end.x - segment.start.x),
  });
  halfEdges.push({
    key: reverseKey,
    twinKey: forwardKey,
    curveId: segment.curveId,
    from: to,
    to: from,
    fromPoint: segment.end,
    toPoint: segment.start,
    curveT0: segment.curveT1,
    curveT1: segment.curveT0,
    curveForward: !segment.curveForward,
    angle: Math.atan2(segment.start.y - segment.end.y, segment.start.x - segment.end.x),
  });
}

// 到达当前边终点后，选择其反向边在极角排序中的前一条边，保持沿面域左侧行走。
function nextFaceEdge(edge, outgoing) {
  const edges = outgoing.get(edge.to) || [];
  const twinIndex = edges.findIndex((candidate) => candidate.key === edge.twinKey);
  if (twinIndex < 0 || !edges.length) return null;
  return edges[(twinIndex - 1 + edges.length) % edges.length];
}

// 由半边环生成区域几何。正面积是内部面，负面积是外部无限面。
function buildRegionFromCycle(cycle) {
  if (cycle.length < 2) return null;
  const polygon = [];
  const directedCurveTokens = [];
  for (const edge of cycle) {
    const previous = polygon[polygon.length - 1];
    if (!previous || !pointsClose(previous, edge.fromPoint)) {
      polygon.push(edge.fromPoint);
    }
    directedCurveTokens.push(`${edge.curveId}${edge.curveForward ? "+" : "-"}`);
  }
  if (pointsClose(polygon[0], polygon[polygon.length - 1])) {
    polygon.pop();
  }
  if (polygon.length < 3) return null;
  const area = polygonSignedArea(polygon);
  if (area <= MIN_REGION_AREA) return null;
  const boundaryCurveIds = compressCurveIds(cycle.map((edge) => edge.curveId));
  return {
    boundaryCurveIds,
    boundarySegments: compressRegionBoundarySegments(cycle),
    boundarySignature: normalizeCyclicTokens(compressTokens(directedCurveTokens)).join("|"),
    legacyBoundarySignature: legacyBoundarySignature(boundaryCurveIds),
    polygon,
    centroid: polygonCentroid(polygon, area),
    area,
  };
}

// 保留区域在交点之间实际使用的曲线区间，避免网格阶段把被截断的边界重新扩展成整条曲线。
function compressRegionBoundarySegments(cycle) {
  const segments = [];
  for (const edge of cycle || []) {
    const curveT0 = Number(edge.curveT0);
    const curveT1 = Number(edge.curveT1);
    if (!edge.curveId || !Number.isFinite(curveT0) || !Number.isFinite(curveT1)) continue;
    const previous = segments[segments.length - 1];
    const sameDirection = previous && Math.sign(previous.t1 - previous.t0) === Math.sign(curveT1 - curveT0);
    if (previous?.curveId === edge.curveId && sameDirection && Math.abs(previous.t1 - curveT0) <= REGION_INTERSECTION_TOLERANCE * 4) {
      previous.t1 = curveT1;
      previous.end = roundPoint(edge.toPoint);
      continue;
    }
    segments.push({
      curveId: edge.curveId,
      t0: curveT0,
      t1: curveT1,
      start: roundPoint(edge.fromPoint),
      end: roundPoint(edge.toPoint),
    });
  }
  return segments;
}

// 两线段相交算法：用二维叉积求参数 t/u，t 和 u 都在 [0,1] 内表示交点落在线段上。
function segmentIntersection(a, b, c, d) {
  const r = { x: b.x - a.x, y: b.y - a.y };
  const s = { x: d.x - c.x, y: d.y - c.y };
  const denominator = cross(r, s);
  if (Math.abs(denominator) < REGION_INTERSECTION_TOLERANCE) {
    return null;
  }
  const cma = { x: c.x - a.x, y: c.y - a.y };
  const t = cross(cma, s) / denominator;
  const u = cross(cma, r) / denominator;
  if (
    t < -REGION_INTERSECTION_TOLERANCE ||
    t > 1 + REGION_INTERSECTION_TOLERANCE ||
    u < -REGION_INTERSECTION_TOLERANCE ||
    u > 1 + REGION_INTERSECTION_TOLERANCE
  ) {
    return null;
  }
  return {
    t: clamp(t, 0, 1),
    u: clamp(u, 0, 1),
    point: pointOnSegment(a, b, clamp(t, 0, 1)),
  };
}

// 二维叉积，符号表示转向，绝对值表示平行四边形面积。
function cross(a, b) {
  return a.x * b.y - a.y * b.x;
}

// 按参数 t 取得线段上的插值点，t=0 为起点，t=1 为终点。
function pointOnSegment(a, b, t) {
  return {
    x: lerp(a.x, b.x, t),
    y: lerp(a.y, b.y, t),
  };
}

// 交点参数去重排序，避免相邻极近切分点产生零长度半边。
function uniqueSortedParameters(parameters) {
  return [...parameters]
    .map((value) => clamp(Number(value), 0, 1))
    .filter(Number.isFinite)
    .sort((a, b) => a - b)
    .filter((value, index, sorted) => index === 0 || Math.abs(value - sorted[index - 1]) > REGION_INTERSECTION_TOLERANCE);
}

// 将坐标按容差量化成字符串键，用于把几何上非常接近的端点合并为同一图节点。
function regionPointKey(point) {
  const scale = 1 / REGION_POINT_MERGE_TOLERANCE;
  return `${Math.round(point.x * scale)}:${Math.round(point.y * scale)}`;
}

// 压缩连续重复曲线 ID；一条曲线被采样成多段后，区域边界仍只希望显示一次曲线编号。
function compressCurveIds(curveIds) {
  const compressed = [];
  for (const curveId of curveIds) {
    if (compressed[compressed.length - 1] !== curveId) {
      compressed.push(curveId);
    }
  }
  if (compressed.length > 1 && compressed[0] === compressed[compressed.length - 1]) {
    compressed.pop();
  }
  return compressed;
}

// 压缩连续重复的有向曲线标记，保留曲线方向信息用于更稳定地区分区域。
function compressTokens(tokens) {
  const compressed = [];
  for (const token of tokens) {
    if (compressed[compressed.length - 1] !== token) {
      compressed.push(token);
    }
  }
  if (compressed.length > 1 && compressed[0] === compressed[compressed.length - 1]) {
    compressed.pop();
  }
  return compressed;
}

// 闭合环没有固定起点，按字典序旋转到最小形式，作为可比较的区域签名。
function normalizeCyclicTokens(tokens) {
  if (!tokens.length) return [];
  let best = tokens;
  for (let i = 1; i < tokens.length; i++) {
    const rotated = [...tokens.slice(i), ...tokens.slice(0, i)];
    if (rotated.join("|") < best.join("|")) {
      best = rotated;
    }
  }
  return best;
}

// 旧版本区域只用无方向曲线集合做签名，导入旧 JSON 时用它恢复材料填充。
function legacyBoundarySignature(curveIds) {
  return [...new Set(curveIds || [])].sort().join("|");
}

// 将区域类型归一化为 structure/air，兼容英文别名、中文别名和旧版布尔值。
function normalizeRegionKind(value) {
  if (value === true) return REGION_KIND_AIR;
  if (typeof value !== "string") return REGION_KIND_STRUCTURE;
  const normalized = value.trim().toLowerCase();
  return ["air", "void", "cavity", "hole", "outside", "external", "empty", "空气", "空腔", "孔洞", "外部", "外部空气"].includes(normalized)
    ? REGION_KIND_AIR
    : REGION_KIND_STRUCTURE;
}

// 判断区域是否是外部空气/孔洞。空气区域不参与结构材料分类。
function isAirRegion(region) {
  return normalizeRegionKind(region?.regionKind ?? region?.kind ?? region?.type ?? region?.isAir) === REGION_KIND_AIR;
}

// 区域类型显示文字。
function regionKindLabel(region) {
  return isAirRegion(region) ? "外部空气" : "结构";
}

// 写入区域类型，同时保证空气区域清空材料信息。
function setRegionKindData(region, kind) {
  const regionKind = normalizeRegionKind(kind);
  region.regionKind = regionKind;
  region.isAir = regionKind === REGION_KIND_AIR;
  region.isStructure = regionKind === REGION_KIND_STRUCTURE;
  if (region.isAir) {
    setRegionMaterialData(region, null);
  }
}

// 多边形有向面积；世界坐标为 y 向上，因此逆时针区域为正。
function polygonSignedArea(points) {
  let sum = 0;
  for (let i = 0; i < points.length; i++) {
    const a = points[i];
    const b = points[(i + 1) % points.length];
    sum += a.x * b.y - b.x * a.y;
  }
  return sum / 2;
}

// 多边形质心；退化时退回顶点平均值。
function polygonCentroid(points, signedArea = polygonSignedArea(points)) {
  if (Math.abs(signedArea) < 1e-12) {
    const sum = points.reduce((acc, point) => ({ x: acc.x + point.x, y: acc.y + point.y }), { x: 0, y: 0 });
    return { x: sum.x / points.length, y: sum.y / points.length };
  }
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < points.length; i++) {
    const a = points[i];
    const b = points[(i + 1) % points.length];
    const cross = a.x * b.y - b.x * a.y;
    cx += (a.x + b.x) * cross;
    cy += (a.y + b.y) * cross;
  }
  return {
    x: cx / (6 * signedArea),
    y: cy / (6 * signedArea),
  };
}

// 给新识别的区域分配最小可用 R 编号。
function allocateRegionId(regions) {
  const used = new Set(regions.map((region) => region.id));
  let value = 1;
  while (used.has(`R${value}`)) {
    value++;
  }
  return `R${value}`;
}

// 未填充材料时给不同结构区域一个淡色，便于区分。
function regionDefaultColor(id, index = 0) {
  const numeric = Number(String(id || "").replace(/\D/g, "")) || index + 1;
  return REGION_PALETTE[(numeric - 1) % REGION_PALETTE.length];
}

// 坐标点统一按模型坐标精度取整，避免区域 JSON 中出现长浮点尾数。
function roundPoint(point) {
  return {
    x: roundCoord(point.x),
    y: roundCoord(point.y),
  };
}

// 判断点对象是否包含有效 x/y 数值；曲线采样异常时会被过滤。
function isFinitePoint(point) {
  return Number.isFinite(point?.x) && Number.isFinite(point?.y);
}

// 判断两个点在容差内是否可视为同一点，用于闭合环去重和端点合并。
function pointsClose(a, b, tolerance = 1e-7) {
  return Boolean(a && b && distance(a, b) <= tolerance);
}

// 返回包含指定点的所有结构区域，供右键填充、节点分类和单元分类共同使用。
function getStructureRegionsAtPoint(point, tolerance = DEFAULT_CLASSIFICATION_TOLERANCE) {
  const safeTolerance = normalizeTolerance(tolerance);
  return (scene.regions || [])
    .filter((region) => pointInRegion(point, region, safeTolerance))
    .map(regionInfo)
    .sort((a, b) => a.area - b.area || a.id.localeCompare(b.id));
}

// 返回指定点所在的结构区域；嵌套或重叠时优先取面积最小者。
function getStructureRegionAtPoint(point, tolerance = DEFAULT_CLASSIFICATION_TOLERANCE) {
  return getStructureRegionsAtPoint(point, tolerance)[0] || null;
}

// 查询某个坐标点继承到的材料快照；后续求解器可用它组装材料矩阵。
function getMaterialAtPoint(point, tolerance = DEFAULT_CLASSIFICATION_TOLERANCE) {
  return getStructureRegionAtPoint(point, tolerance)?.material || null;
}

// 区域包含判断：边界容差命中视为在区域内，否则使用射线奇偶法判断多边形内部。
function pointInRegion(point, region, tolerance = 0) {
  const polygon = Array.isArray(region?.polygon) ? region.polygon : [];
  if (polygon.length < 3) return false;
  if (pointOnPolygonBoundary(point, polygon, tolerance)) return true;
  return pointInPolygon(point, polygon);
}

// 点到多边形每条边的最短距离小于容差时，认为点在边界上。
function pointOnPolygonBoundary(point, polygon, tolerance) {
  if (tolerance <= 0) return false;
  for (let i = 0; i < polygon.length; i++) {
    if (distanceToSegment(point, polygon[i], polygon[(i + 1) % polygon.length]) <= tolerance) {
      return true;
    }
  }
  return false;
}

// 射线奇偶算法：从点向右发射水平射线，穿过边界次数为奇数则在多边形内。
function pointInPolygon(point, polygon) {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[i];
    const b = polygon[j];
    const crosses = a.y > point.y !== b.y > point.y;
    if (crosses) {
      const x = ((b.x - a.x) * (point.y - a.y)) / (b.y - a.y) + a.x;
      if (point.x < x) inside = !inside;
    }
  }
  return inside;
}

// 对外返回区域信息时同时带上当前材料库或区域快照中的材料属性。
function regionInfo(region) {
  const material = materialSnapshotForRegion(region);
  const air = isAirRegion(region);
  return {
    id: region.id,
    regionId: region.id,
    structureRegionId: region.id,
    name: region.name,
    regionKind: air ? REGION_KIND_AIR : REGION_KIND_STRUCTURE,
    isAir: air,
    isStructure: !air,
    boundaryCurveIds: [...(region.boundaryCurveIds || [])],
    centroid: region.centroid ? { ...region.centroid } : null,
    area: region.area,
    materialId: material?.id || null,
    materialName: material?.name || "",
    materialColor: material?.color || "",
    materialProperties: material ? materialMechanicalProperties(material) : null,
    material,
  };
}

// 把区域信息压缩成可写到节点/单元上的分类字段。
function regionClassificationFields(region) {
  const air = isAirRegion(region);
  return {
    structureRegionId: region?.structureRegionId || region?.id || null,
    regionId: region?.regionId || region?.id || null,
    structureName: region?.name || "",
    regionKind: region ? (air ? REGION_KIND_AIR : REGION_KIND_STRUCTURE) : null,
    isAir: Boolean(region && air),
    isStructure: Boolean(region && !air),
    materialId: region?.materialId || null,
    materialName: region?.materialName || "",
    materialColor: region?.materialColor || "",
    materialProperties: region?.materialProperties || null,
  };
}

// 按材料 ID 从当前材料库查找完整材料。
function materialById(id) {
  return materialLibrary.find((material) => material.id === id) || null;
}

// 取得区域当前材料快照：优先使用材料库最新值，其次兼容导入文件中的旧快照字段。
function materialSnapshotForRegion(region) {
  if (!region) return null;
  if (isAirRegion(region)) return null;
  const libraryMaterial = region.materialId ? materialById(region.materialId) : null;
  return createMaterialSnapshot(libraryMaterial || region.material || region.materialSnapshot || materialFromRegionFields(region));
}

// 从区域平铺字段恢复材料对象，兼容早期导出格式。
function materialFromRegionFields(region) {
  if (!region?.materialId && !region?.materialName && !region?.materialProperties) return null;
  return {
    id: region.materialId,
    name: region.materialName,
    color: region.materialColor,
    ...(region.materialProperties || {}),
  };
}

// 创建可嵌入区域、节点和单元的材料快照，避免外部修改材料库时旧文件丢失必要属性。
function createMaterialSnapshot(raw) {
  if (!raw) return null;
  const id = String(raw.id || raw.materialId || "").trim();
  const name = String(raw.name || raw.materialName || "").trim();
  if (!id && !name) return null;
  return {
    id,
    name,
    elasticModulus: nullableNumber(raw.elasticModulus),
    poissonRatio: nullableNumber(raw.poissonRatio),
    density: nullableNumber(raw.density),
    yieldStrength: nullableNumber(raw.yieldStrength),
    tensileStrength: nullableNumber(raw.tensileStrength),
    compressiveStrength: nullableNumber(raw.compressiveStrength),
    color: normalizeColor(raw.color || raw.materialColor),
    sourceUrl: String(raw.sourceUrl || "").trim(),
    sourceUrls: Array.isArray(raw.sourceUrls) ? raw.sourceUrls.map((url) => String(url).trim()).filter(Boolean) : [],
    notes: String(raw.notes || "").trim(),
  };
}

// 抽取有限元求解常用的材料力学属性。
function materialMechanicalProperties(material) {
  return {
    elasticModulus: material.elasticModulus,
    poissonRatio: material.poissonRatio,
    density: material.density,
    yieldStrength: material.yieldStrength,
    tensileStrength: material.tensileStrength,
    compressiveStrength: material.compressiveStrength,
  };
}

// 将材料快照写入区域；空气区域强制清空材料。
function setRegionMaterialData(region, material) {
  const snapshot = isAirRegion(region) ? null : createMaterialSnapshot(material);
  region.materialId = snapshot?.id || null;
  region.materialName = snapshot?.name || "";
  region.materialColor = snapshot?.color || "";
  region.materialProperties = snapshot ? materialMechanicalProperties(snapshot) : null;
  region.material = snapshot;
}

// 材料库编辑后，把引用同一材料 ID 的区域同步到最新材料属性。
function syncRegionMaterialSnapshots() {
  for (const region of scene.regions || []) {
    const current = region.materialId ? materialById(region.materialId) : null;
    if (current) {
      setRegionMaterialData(region, current);
    }
  }
}
