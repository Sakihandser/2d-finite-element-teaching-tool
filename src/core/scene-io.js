// 清空当前场景，但保留模型名称。
function clearScene() {
  closeShapeEditor();
  const keepName = scene.name;
  scene = emptyScene();
  scene.name = keepName;
  selected = null;
  draft = null;
  hideRegionMaterialMenu();
  updatePanel();
  render();
}

// 将当前 scene 和视图状态导出为 JSON 文件。
function exportScene() {
  scene.name = modelName.value.trim() || "未命名模型";
  syncRegionMaterialSnapshots();
  classifyAnalysisElements();
  const payload = {
    ...scene,
    viewport: {
      offsetX: view.offsetX,
      offsetY: view.offsetY,
      scale: view.scale,
    },
    calculationViewport: getCalculationViewState(),
  };
  const blob = new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${scene.name || "fem-sketch"}.json`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

// 读取用户选择的 JSON 文件，并恢复为内部 scene 数据。
function importScene(file) {
  const reader = new FileReader();
  reader.onload = () => {
    try {
      const data = JSON.parse(reader.result);
      closeShapeEditor();
      scene = normalizeScene(data);
      modelName.value = uiText(scene.name);
      selected = null;
      draft = null;
      hideRegionMaterialMenu();
      rebuildDerivedRegions({ markAnalysisNodePlacementStale: false });
      if (data.viewport?.scale) {
        view.scale = clamp(Number(data.viewport.scale), 8, 500);
        view.offsetX = Number(data.viewport.offsetX) || view.width / 2;
        view.offsetY = Number(data.viewport.offsetY) || view.height / 2;
      } else {
        fitViewToScene();
      }
      if (data.calculationViewport?.scale) {
        setCalculationViewState(data.calculationViewport);
      } else {
        fitCalculationViewToScene();
      }
      if (scene.analysisNodes.length) {
        classifyAnalysisNodes();
      }
      updatePanel();
      render();
    } catch (error) {
      window.alert(`导入失败：${error.message}`);
    }
  };
  reader.readAsText(file);
}

// 对导入数据做类型修正和默认值填充，避免旧文件或手改 JSON 导致运行错误。
function normalizeScene(data) {
  const next = emptyScene();
  // 导入时逐项拷贝，避免外部 JSON 中混入额外字段影响运行状态。
  next.version = 6;
  next.name = String(data.name || "未命名模型");

  const rawGeometryNodes = Array.isArray(data.geometryNodes)
    ? data.geometryNodes
    : Array.isArray(data.nodes)
      ? data.nodes
      : [];
  const migrateOldNodeIds = !Array.isArray(data.geometryNodes) && Array.isArray(data.nodes);
  const geometryIdMap = new Map();
  next.geometryNodes = rawGeometryNodes.map((node, index) => {
    const oldId = String(node.id || `N${index + 1}`);
    const id = migrateOldNodeIds ? `G${index + 1}` : oldId;
    geometryIdMap.set(oldId, id);
    return {
      id,
      x: Number(node.x) || 0,
      y: Number(node.y) || 0,
      mechanicalState: normalizeMechanicalState(node.mechanicalState ?? node.boundaryState ?? node.supportState ?? node.isStatic),
      previewUx: Number(node.previewUx ?? node.ux) || 0,
      previewUy: Number(node.previewUy ?? node.uy) || 0,
      autoGenerated: Boolean(node.autoGenerated),
      autoRole: String(node.autoRole || ""),
      intersectionCurveIds: Array.isArray(node.intersectionCurveIds) ? node.intersectionCurveIds.map(String) : [],
    };
  });

  const mapGeometryNodeId = (id) => geometryIdMap.get(String(id)) || String(id);
  next.curves = Array.isArray(data.curves)
    ? data.curves
        .map((curve, index) => {
          const rawIds = Array.isArray(curve.geometryNodeIds)
            ? curve.geometryNodeIds
            : Array.isArray(curve.nodeIds)
              ? curve.nodeIds
              : [];
          return {
            id: String(curve.id || `C${index + 1}`),
            type: ["line", "quadratic", "cubic", "arc", "ellipse"].includes(curve.type) ? curve.type : "line",
            mechanicalState: normalizeMechanicalState(curve.mechanicalState ?? curve.boundaryState ?? curve.supportState ?? curve.isStatic),
            geometryNodeIds: rawIds.map(mapGeometryNodeId).slice(0, 2),
            controls: Array.isArray(curve.controls)
              ? curve.controls.map((point) => ({ x: Number(point.x) || 0, y: Number(point.y) || 0 })).slice(0, 2)
              : [],
          };
        })
        .filter((curve) => curve.geometryNodeIds.length >= 2)
    : [];

  next.regions = Array.isArray(data.regions)
    ? data.regions.map(normalizeImportedRegion).filter((region) => region.boundaryCurveIds.length >= 2)
    : [];

  next.pointLoads = Array.isArray(data.pointLoads)
    ? data.pointLoads.map((load, index) => {
        // load.nodeId 是旧版字段，导入后统一迁移为 geometryNodeId。
        const rawGeometryNodeId = load.geometryNodeId ?? load.nodeId;
        return {
          id: String(load.id || `F${index + 1}`),
          geometryNodeId: rawGeometryNodeId !== undefined && rawGeometryNodeId !== null ? mapGeometryNodeId(rawGeometryNodeId) : null,
          anchor: load.anchor ? { x: Number(load.anchor.x) || 0, y: Number(load.anchor.y) || 0 } : { x: 0, y: 0 },
          fx: Number(load.fx) || 0,
          fy: Number(load.fy) || 0,
          label: String(load.label || "F"),
        };
      })
    : [];

  next.distributedLoads = Array.isArray(data.distributedLoads)
    ? data.distributedLoads.map((load, index) => ({
        id: String(load.id || `Q${index + 1}`),
        curveId: String(load.curveId || ""),
        q: Number(load.qStart ?? load.q) || 0,
        qStart: Math.abs(Number(load.qStart ?? load.q) || 0),
        qEnd: Math.abs(Number(load.qEnd ?? load.qStart ?? load.q) || 0),
        direction: load.direction
          ? normalize({ x: Number(load.direction.x) || 0, y: Number(load.direction.y) || 0 }, { x: 0, y: -1 })
          : { x: 0, y: -1 },
        start: clamp(Number(load.start) || 0, 0, 1),
        end: clamp(Number(load.end ?? 1), 0, 1),
        label: String(load.label || "q"),
      }))
    : [];

  next.bodyLoads = Array.isArray(data.bodyLoads)
    ? data.bodyLoads.map((load, index) => {
        const regionId = load.regionId !== undefined && load.regionId !== null ? String(load.regionId) : null;
        const targetType = load.targetType === "region" || regionId ? "region" : "global";
        return {
          id: String(load.id || `B${index + 1}`),
          targetType,
          regionId: targetType === "region" ? regionId : null,
          magnitude: Math.abs(Number(load.magnitude ?? load.g ?? load.acceleration) || 0),
          direction: load.direction
            ? normalize({ x: Number(load.direction.x) || 0, y: Number(load.direction.y) || 0 }, { x: 0, y: -1 })
            : { x: 0, y: -1 },
          label: String(load.label || "g"),
        };
      })
    : [];

  const rawAnalysisNodes = Array.isArray(data.analysisNodes)
    ? data.analysisNodes
    : Array.isArray(data.mesh?.nodes)
      ? data.mesh.nodes
      : [];
  next.analysisNodes = rawAnalysisNodes.map((node, index) => ({
    id: String(node.id || `A${index + 1}`),
    x: Number(node.x) || 0,
    y: Number(node.y) || 0,
    placement: normalizeAnalysisNodePlacementObject(node.placement || node.analysisPlacement),
    mechanicalState: normalizeMechanicalState(node.mechanicalState),
    isStatic: normalizeMechanicalState(node.mechanicalState) === "static",
    isFree: normalizeMechanicalState(node.mechanicalState) === "free",
    geometrySourceType: node.geometrySourceType || null,
    geometrySourceId: node.geometrySourceId || null,
    geometrySourceDistance: Number.isFinite(Number(node.geometrySourceDistance)) ? Number(node.geometrySourceDistance) : null,
    structureRegionId: node.structureRegionId || node.regionId || null,
    regionId: node.regionId || node.structureRegionId || null,
    structureName: String(node.structureName || ""),
    regionKind: node.regionKind ? normalizeRegionKind(node.regionKind) : null,
    isAir: Boolean(node.isAir),
    isStructure: Boolean(node.isStructure),
    materialId: node.materialId || null,
    materialName: String(node.materialName || ""),
    materialColor: String(node.materialColor || ""),
    materialProperties: node.materialProperties || null,
    ux: Number(node.ux) || 0,
    uy: Number(node.uy) || 0,
  }));
  next.mesh = {
    elements: Array.isArray(data.mesh?.elements) ? data.mesh.elements.map(normalizeMeshElement) : [],
    metadata: normalizeAnalysisMeshMetadata(data.mesh?.metadata || data.meshMetadata),
  };
  next.analysisNodePlacement = normalizeAnalysisNodePlacementData(data.analysisNodePlacement);
  next.nextIds = {
    geometryNode: maxNumericId(next.geometryNodes, "G") + 1,
    analysisNode: maxNumericId(next.analysisNodes, "A") + 1,
    curve: maxNumericId(next.curves, "C") + 1,
    region: maxNumericId(next.regions, "R") + 1,
    pointLoad: maxNumericId(next.pointLoads, "F") + 1,
    distributedLoad: maxNumericId(next.distributedLoads, "Q") + 1,
    bodyLoad: maxNumericId(next.bodyLoads, "B") + 1,
  };
  applyStaticBoundaryEndpointStates(next);
  return next;
}

// 规整导入文件中的区域数据，并恢复旧版本保存的材料快照与边界签名。
function normalizeImportedRegion(region, index) {
  const material = createMaterialSnapshot(region.material || region.materialSnapshot || materialFromRegionFields(region));
  const regionKind = normalizeRegionKind(region.regionKind ?? region.kind ?? region.type ?? region.isAir);
  const normalized = {
    id: String(region.id || `R${index + 1}`),
    name: String(region.name || region.label || `结构 R${index + 1}`),
    regionKind,
    isAir: regionKind === REGION_KIND_AIR,
    isStructure: regionKind === REGION_KIND_STRUCTURE,
    boundaryCurveIds: Array.isArray(region.boundaryCurveIds) ? region.boundaryCurveIds.map(String) : [],
    boundarySignature: String(region.boundarySignature || ""),
    legacyBoundarySignature: String(region.legacyBoundarySignature || ""),
    polygon: Array.isArray(region.polygon) ? region.polygon.map((point) => ({ x: Number(point.x) || 0, y: Number(point.y) || 0 })) : [],
    centroid: region.centroid ? { x: Number(region.centroid.x) || 0, y: Number(region.centroid.y) || 0 } : null,
    area: Number(region.area) || 0,
    signedArea: Number(region.signedArea) || Number(region.area) || 0,
    fillColor: normalizeColor(region.fillColor),
    materialId: null,
    materialName: "",
    materialColor: "",
    materialProperties: null,
    material: null,
  };
  if (!normalized.boundarySignature && normalized.boundaryCurveIds.length) {
    normalized.boundarySignature = [...new Set(normalized.boundaryCurveIds)].sort().join("|");
  }
  if (!normalized.legacyBoundarySignature && normalized.boundaryCurveIds.length) {
    normalized.legacyBoundarySignature = legacyBoundarySignature(normalized.boundaryCurveIds);
  }
  setRegionMaterialData(normalized, normalized.isAir ? null : material);
  return normalized;
}

// 从已有 ID 中找出最大数字，用于导入后初始化 nextIds。
function maxNumericId(items, prefix) {
  return items.reduce((max, item) => {
    const match = String(item.id || "").match(new RegExp(`^${prefix}(\\d+)$`));
    return match ? Math.max(max, Number(match[1])) : max;
  }, 0);
}
