// 生成对象 ID。这里扫描现有编号，返回最小可用序号，删除 G3 后会优先复用 G3。
function nextId(type) {
  const prefix = idPrefixForType(type);
  // 收集当前已经占用的编号数字，例如 G1/G2/G4 会得到 {1, 2, 4}。
  const usedNumbers = new Set(
    itemsForIdType(type)
      .map((item) => String(item.id || "").match(new RegExp(`^${prefix}(\\d+)$`)))
      .filter(Boolean)
      .map((match) => Number(match[1])),
  );
  // 从 1 开始找第一个空号，因此删除 G3 后下一次会生成 G3。
  let value = 1;
  while (usedNumbers.has(value)) {
    value++;
  }
  scene.nextIds[type] = value + 1;
  return `${prefix}${value}`;
}

// 根据对象类型取得 ID 前缀。
function idPrefixForType(type) {
  if (type === "geometryNode") return "G";
  if (type === "analysisNode") return "A";
  if (type === "curve") return "C";
  if (type === "region") return "R";
  if (type === "pointLoad") return "F";
  if (type === "distributedLoad") return "Q";
  return "B";
}

// 根据对象类型取得对应数组，用于编号扫描。
function itemsForIdType(type) {
  if (type === "geometryNode") return scene.geometryNodes;
  if (type === "analysisNode") return scene.analysisNodes;
  if (type === "curve") return scene.curves;
  if (type === "region") return scene.regions || [];
  if (type === "pointLoad") return scene.pointLoads;
  if (type === "distributedLoad") return scene.distributedLoads;
  return scene.bodyLoads || [];
}

// 在指定世界坐标创建几何节点。几何节点只描述模型轮廓，不参与刚度矩阵编号。
function createGeometryNode(point, options = {}) {
  const node = {
    id: nextId("geometryNode"),
    x: roundCoord(point.x),
    y: roundCoord(point.y),
    mechanicalState: normalizeMechanicalState(options.mechanicalState),
    previewUx: 0,
    previewUy: 0,
    autoGenerated: Boolean(options.autoGenerated),
    autoRole: options.autoRole || "",
    intersectionCurveIds: Array.isArray(options.intersectionCurveIds) ? [...options.intersectionCurveIds] : [],
  };
  scene.geometryNodes.push(node);
  if (options.select !== false) {
    selectObject("geometryNode", node.id);
  }
  if (options.update !== false) {
    updatePanel();
  }
  return node;
}

// 创建曲线边界；geometryNodeIds 保存几何端点，controls 只保存曲线形状控制点。
function createCurve(type, geometryNodeIds, controls = []) {
  const curve = {
    id: nextId("curve"),
    type,
    mechanicalState: "free",
    geometryNodeIds,
    controls: controls.map((point) => ({
      x: roundCoord(point.x),
      y: roundCoord(point.y),
    })),
  };
  scene.curves.push(curve);
  rebuildDerivedRegions();
  selectObject("curve", curve.id);
  updatePanel();
  return curve;
}

// 创建作用在几何节点或自由位置上的点载荷，后续网格化时再转换为计算节点上的等效载荷。
function createPointLoad(anchor, vector, geometryNodeId = null) {
  const magnitude = Math.abs(readNumber(forceMagnitude, 10));
  // vector 只用于方向，长度由 magnitude 统一控制。
  const unit = normalize(vector, { x: 0, y: -1 });
  const load = {
    id: nextId("pointLoad"),
    geometryNodeId,
    anchor: {
      x: roundCoord(anchor.x),
      y: roundCoord(anchor.y),
    },
    fx: roundCoord(unit.x * magnitude),
    fy: roundCoord(unit.y * magnitude),
    label: "F",
  };
  scene.pointLoads.push(load);
  selectObject("pointLoad", load.id);
  updatePanel();
  return load;
}

// 创建沿曲线的分布力，vector 只决定方向，大小来自左侧 q 输入框。
function createDistributedLoad(curveId, vector) {
  const startMagnitude = Math.abs(readNumber(loadMagnitude, 5));
  const endMagnitude = Math.abs(readNumber(loadEndMagnitude, startMagnitude));
  // 分布力保存单位方向和标量 q，便于后续有限元载荷等效转换。
  const unit = normalize(vector, { x: 0, y: -1 });
  const load = {
    id: nextId("distributedLoad"),
    curveId,
    q: roundCoord(startMagnitude),
    qStart: roundCoord(startMagnitude),
    qEnd: roundCoord(endMagnitude),
    direction: {
      x: roundCoord(unit.x),
      y: roundCoord(unit.y),
    },
    start: 0,
    end: 1,
    label: "q",
  };
  scene.distributedLoads.push(load);
  selectObject("distributedLoad", load.id);
  updatePanel();
  return load;
}

// 创建体力载荷；全局体力作用于全部结构区域，区域体力只作用于指定结构区域。
function createBodyForceLoad(regionId = null) {
  const magnitude = Math.abs(readNumber(bodyForceMagnitude, 9.81));
  const unit = normalize(presetLoadDirection(), { x: 0, y: -1 });
  const targetRegionId = regionId ? String(regionId) : null;
  const load = {
    id: nextId("bodyLoad"),
    targetType: targetRegionId ? "region" : "global",
    regionId: targetRegionId,
    magnitude: roundCoord(magnitude),
    direction: {
      x: roundCoord(unit.x),
      y: roundCoord(unit.y),
    },
    label: "g",
  };
  scene.bodyLoads = scene.bodyLoads || [];
  scene.bodyLoads.push(load);
  selectObject("bodyLoad", load.id);
  updatePanel();
  return load;
}

// 读取分布力起点强度；旧模型没有 qStart 时退回到 q。
function distributedLoadStartMagnitude(load) {
  const value = Number(load?.qStart);
  if (Number.isFinite(value)) return Math.abs(value);
  return Math.abs(Number(load?.q) || 0);
}

// 读取分布力终点强度；旧模型没有 qEnd 时退回到起点强度。
function distributedLoadEndMagnitude(load) {
  const value = Number(load?.qEnd);
  if (Number.isFinite(value)) return Math.abs(value);
  return distributedLoadStartMagnitude(load);
}

// 按曲线参数读取线性分布力强度。
function distributedLoadMagnitudeAt(load, t) {
  const start = clamp(Number(load?.start) || 0, 0, 1);
  const end = clamp(Number(load?.end ?? 1), 0, 1);
  const span = end - start;
  if (Math.abs(span) < 1e-9) return distributedLoadStartMagnitude(load);
  const ratio = clamp((Number(t) - start) / span, 0, 1);
  return lerp(distributedLoadStartMagnitude(load), distributedLoadEndMagnitude(load), ratio);
}

// 取得整组分布力的最大显示长度。只在整组层面限幅，避免逐根箭头限幅破坏线性包络。
function distributedLoadMaxDisplayLength(load) {
  const maxMagnitude = Math.max(distributedLoadStartMagnitude(load), distributedLoadEndMagnitude(load));
  if (maxMagnitude <= 1e-9) return 0;
  return clamp(maxMagnitude * 7, 26, 72);
}

// 按同一显示比例换算箭头长度，使箭头端点保持与 qStart→qEnd 完全一致的线性变化。
function distributedLoadDisplayLengthAt(load, t) {
  const maxMagnitude = Math.max(distributedLoadStartMagnitude(load), distributedLoadEndMagnitude(load));
  if (maxMagnitude <= 1e-9) return 0;
  return (distributedLoadMagnitudeAt(load, t) / maxMagnitude) * distributedLoadMaxDisplayLength(load);
}

// 体力大小；非法值按 0 处理。
function bodyLoadMagnitude(load) {
  const value = Number(load?.magnitude);
  return Number.isFinite(value) ? Math.abs(value) : 0;
}

// 读取数值输入框，非法输入时使用 fallback。
function readNumber(input, fallback) {
  if (!input) return fallback;
  const value = Number(input.value);
  return Number.isFinite(value) ? value : fallback;
}

// 坐标保留到 1e-6，减少 JSON 中的浮点噪声。
function roundCoord(value) {
  return Math.round(value * 1000000) / 1000000;
}

