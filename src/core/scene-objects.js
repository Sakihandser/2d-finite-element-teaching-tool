let analysisNodeLookupCache = {
  source: null,
  length: -1,
  firstId: null,
  lastId: null,
  byId: new Map(),
};

function analysisNodeLookup(force = false) {
  const nodes = scene.analysisNodes || [];
  const firstId = nodes.length ? String(nodes[0].id) : null;
  const lastId = nodes.length ? String(nodes[nodes.length - 1].id) : null;
  if (
    force ||
    analysisNodeLookupCache.source !== nodes ||
    analysisNodeLookupCache.length !== nodes.length ||
    analysisNodeLookupCache.firstId !== firstId ||
    analysisNodeLookupCache.lastId !== lastId
  ) {
    analysisNodeLookupCache = {
      source: nodes,
      length: nodes.length,
      firstId,
      lastId,
      byId: new Map(nodes.map((node) => [String(node.id), node])),
    };
  }
  return analysisNodeLookupCache.byId;
}

// 按 ID 或数组下标查找计算节点；ID 索引避免大网格绘制和分类时反复线性扫描全部节点。
function analysisNodeByRef(ref) {
  if (typeof ref === "number") return scene.analysisNodes[ref];
  const key = String(ref);
  const lookup = analysisNodeLookup();
  if (lookup.has(key)) return lookup.get(key);
  return analysisNodeLookup(true).get(key);
}

// 取得几何节点位置；这里的 previewUx/previewUy 只用于图形预览，不是求解位移。
function getGeometryNodePosition(node, animated = false) {
  if (!node) {
    return { x: 0, y: 0 };
  }
  if (!animated || !animation.running) {
    return { x: node.x, y: node.y };
  }
  const scale = readNumber(animationScale, 1);
  const phase = Number(node.id.replace(/\D/g, "")) || 0;
  const ux = node.previewUx || 0;
  const uy = node.previewUy || 0;
  const fallbackUx = Math.sin(animation.time * 1.7 + phase) * 0.035;
  const fallbackUy = Math.cos(animation.time * 1.3 + phase * 0.7) * 0.035;
  return {
    x: node.x + (ux || fallbackUx) * scale,
    y: node.y + (uy || fallbackUy) * scale,
  };
}

// 取得曲线两端几何节点的坐标，可选择是否使用动画预览后的节点位置。
function getCurveAnchors(curve, animated = false) {
  return curve.geometryNodeIds.map((id) => getGeometryNodePosition(geometryNodeById(id), animated));
}

// 根据曲线类型和参数 t 计算曲线上一点，t 范围为 0 到 1。
function pointOnCurve(curve, t, animated = false) {
  const anchors = getCurveAnchors(curve, animated);
  const p0 = anchors[0];
  const p1 = anchors[1];
  if (!p0 || !p1) {
    return { x: 0, y: 0 };
  }
  if (curve.type === "line") {
    return lerpPoint(p0, p1, t);
  }
  if (curve.type === "quadratic") {
    const c = curve.controls[0] || midpoint(p0, p1);
    return quadraticPoint(p0, c, p1, t);
  }
  if (curve.type === "cubic") {
    const c1 = curve.controls[0] || lerpPoint(p0, p1, 0.33);
    const c2 = curve.controls[1] || lerpPoint(p0, p1, 0.67);
    return cubicPoint(p0, c1, c2, p1, t);
  }
  if (curve.type === "arc") {
    const through = curve.controls[0] || midpoint(p0, p1);
    return arcPoint(p0, through, p1, t);
  }
  return lerpPoint(p0, p1, t);
}

// 将曲线离散采样为一串点，用于 canvas 绘制和命中测试。
function sampleCurve(curve, count = 48, animated = false) {
  const points = [];
  for (let i = 0; i <= count; i++) {
    points.push(pointOnCurve(curve, i / count, animated));
  }
  return points;
}

// 标量线性插值。
function lerp(a, b, t) {
  return a + (b - a) * t;
}

// 二维点线性插值。
function lerpPoint(a, b, t) {
  return { x: lerp(a.x, b.x, t), y: lerp(a.y, b.y, t) };
}

// 两点中点。
function midpoint(a, b) {
  return { x: (a.x + b.x) / 2, y: (a.y + b.y) / 2 };
}

// 二次贝塞尔曲线公式。
function quadraticPoint(p0, c, p1, t) {
  const mt = 1 - t;
  return {
    x: mt * mt * p0.x + 2 * mt * t * c.x + t * t * p1.x,
    y: mt * mt * p0.y + 2 * mt * t * c.y + t * t * p1.y,
  };
}

// 三次贝塞尔曲线公式。
function cubicPoint(p0, c1, c2, p1, t) {
  const mt = 1 - t;
  return {
    x: mt ** 3 * p0.x + 3 * mt ** 2 * t * c1.x + 3 * mt * t ** 2 * c2.x + t ** 3 * p1.x,
    y: mt ** 3 * p0.y + 3 * mt ** 2 * t * c1.y + 3 * mt * t ** 2 * c2.y + t ** 3 * p1.y,
  };
}

// 由三点求圆心和半径，圆弧曲线需要这个几何基础。
function circleFromThreePoints(a, b, c) {
  const d = 2 * (a.x * (b.y - c.y) + b.x * (c.y - a.y) + c.x * (a.y - b.y));
  if (Math.abs(d) < 1e-9) {
    return null;
  }
  const aa = a.x * a.x + a.y * a.y;
  const bb = b.x * b.x + b.y * b.y;
  const cc = c.x * c.x + c.y * c.y;
  const x = (aa * (b.y - c.y) + bb * (c.y - a.y) + cc * (a.y - b.y)) / d;
  const y = (aa * (c.x - b.x) + bb * (a.x - c.x) + cc * (b.x - a.x)) / d;
  return {
    center: { x, y },
    radius: distance({ x, y }, a),
  };
}

// 通过起点、过渡点、终点计算圆弧上的参数点；退化时用二次曲线近似。
function arcPoint(start, through, end, t) {
  const circle = circleFromThreePoints(start, through, end);
  if (!circle || circle.radius > 1e6) {
    // 三点共线或半径异常时，圆弧退化为二次曲线，保证界面仍可绘制。
    return quadraticPoint(start, through, end, t);
  }
  const { center, radius } = circle;
  const a0 = Math.atan2(start.y - center.y, start.x - center.x);
  const am = Math.atan2(through.y - center.y, through.x - center.x);
  const a1 = Math.atan2(end.y - center.y, end.x - center.x);
  const ccwDelta = positiveAngle(a1 - a0);
  const midDelta = positiveAngle(am - a0);
  const useCcw = midDelta <= ccwDelta;
  const sweep = useCcw ? ccwDelta : -positiveAngle(a0 - a1);
  const angle = a0 + sweep * t;
  return {
    x: center.x + Math.cos(angle) * radius,
    y: center.y + Math.sin(angle) * radius,
  };
}

// 将角度归一化到 [0, 2π)，便于判断圆弧方向。
function positiveAngle(angle) {
  const twoPi = Math.PI * 2;
  return ((angle % twoPi) + twoPi) % twoPi;
}

// 两点欧氏距离。
function distance(a, b) {
  return Math.hypot(a.x - b.x, a.y - b.y);
}

// 点到整条曲线的近似距离，使用曲线采样线段计算，返回世界坐标距离。
function distanceToCurveWorld(point, curve) {
  const points = sampleCurve(curve, curve.type === "line" ? 1 : 96);
  let bestDistance = Infinity;
  for (let i = 1; i < points.length; i++) {
    bestDistance = Math.min(bestDistance, distanceToSegment(point, points[i - 1], points[i]));
  }
  return bestDistance;
}
