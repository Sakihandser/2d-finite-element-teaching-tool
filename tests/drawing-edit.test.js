"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

function harness() {
  const element = { getContext: () => ({}), value: "", checked: false,
    classList: { toggle() {}, remove() {} }, setPointerCapture() {} };
  const context = vm.createContext({ console, Math, structuredClone,
    window: { devicePixelRatio: 1 },
    uiText: (text) => text, shapeDrag: null,
    fitViewToScene() {}, fitCalculationViewToScene() {}, setCalculationViewState() {},
    document: { getElementById: () => element, querySelectorAll: () => [] },
    updatePanel() {}, render() {}, renderCalculationView() {}, closeShapeEditor() {},
    hideRegionMaterialMenu() {}, assignMaterialToRegion() {}, setRegionKind() {},
    beginShapeDrag: () => false, moveShapeDrag: () => false,
    nearestPointLoad: () => null, nearestDistributedLoad: () => null, nearestBodyLoad: () => null,
    pointerPoint: (event) => ({ x: event.x, y: event.y }),
    worldToScreen: (point) => point, screenToWorld: (point) => point, snapWorld: (point) => point,
  });
  for (const file of ["global/state", "core/numbers", "core/material-utils", "core/scene-objects",
    "core/regular-shapes", "core/regions", "core/analysis-classification", "core/analysis-node-placement",
    "core/analysis-mesh", "pages/drawing/load-hit-testing", "pages/drawing/inspector", "core/scene-io",
    "pages/drawing/interactions", "pages/drawing/selection-actions", "core/calculation-export", "core/drawing-edit"]) {
    vm.runInContext(fs.readFileSync(path.join(__dirname, "../src", file + ".js"), "utf8"), context, { filename: file });
  }
  vm.runInContext("updatePanel = () => {}; installDrawingHistory();", context);
  const run = (code) => vm.runInContext(code, context);
  return { api: context, run, scene: () => run("scene") };
}

function line(h, start, end, construction = false) {
  h.run(`constructionMode = ${construction}`);
  const a = h.api.createGeometryNode(start, { select: false });
  const b = h.api.createGeometryNode(end, { select: false });
  return h.api.createCurve("line", [a.id, b.id]);
}

test("2–5 divisions keep the segment and reuse existing points, with one undo step", () => {
  for (let parts = 2; parts <= 5; parts++) {
    const h = harness();
    line(h, { x: -3, y: 2 }, { x: 7, y: 12 });
    const result = h.api.divideSelectedLine(parts);
    assert.equal(result.length, parts - 1);
    result.forEach((p, i) => {
      assert.ok(Math.abs(p.x - (-3 + 10 * (i + 1) / parts)) < 1e-6);
      assert.ok(Math.abs(p.y - (2 + 10 * (i + 1) / parts)) < 1e-6);
    });
    h.api.divideSelectedLine(parts);
    assert.equal(h.scene().geometryNodes.length, parts + 1);
    assert.equal(h.scene().curves.length, 1);
    h.api.undoDrawing();
    assert.equal(h.scene().geometryNodes.length, 2);
    assert.equal(h.scene().curves.length, 1);
  }
});

test("draft crossing a real region marks intersections without partitioning or adding mandatory nodes", () => {
  const h = harness();
  h.api.createRegularShape({ type: "rectangle", x: 0, y: 0, width: 10, height: 6, angle: 0 });
  const regionId = h.scene().regions[0].id;
  const draft = line(h, { x: 0, y: -4 }, { x: 0, y: 4 }, true);
  assert.equal(h.scene().regions.length, 1);
  assert.equal(h.scene().regions[0].id, regionId);
  const intersections = h.scene().geometryNodes.filter((p) => p.autoGenerated && p.intersectionCurveIds.includes(draft.id));
  assert.equal(intersections.length, 2);
  assert.ok(intersections.every((p) => p.construction));
  const topology = h.api.collectAnalysisPlacementTopology();
  assert.equal(topology.curves.length, 4);
  assert.equal(topology.mandatoryGeometryNodes.length, 4);
  h.api.setSelectedConstruction(false);
  assert.equal(h.scene().regions.length, 2);
  h.api.undoDrawing();
  assert.equal(h.scene().regions.length, 1);
  assert.equal(h.scene().curves.find((p) => p.id === draft.id).construction, true);
});

test("draft–draft intersections can be promoted and demoted independently", () => {
  const h = harness();
  line(h, { x: -5, y: 0 }, { x: 5, y: 0 }, true);
  line(h, { x: 0, y: -5 }, { x: 0, y: 5 }, true);
  const point = h.scene().geometryNodes.find((p) => p.autoGenerated);
  assert.ok(point.construction);
  h.api.selectObject("geometryNode", point.id);
  h.api.setSelectedConstruction(false);
  h.api.rebuildDerivedRegions();
  assert.equal(point.construction, false);
  assert.equal(point.autoGenerated, false);
  assert.ok(h.scene().curves.every((p) => p.construction));
  h.api.setSelectedConstruction(true);
  assert.equal(point.construction, true);
  h.api.undoDrawing();
  assert.equal(h.scene().geometryNodes.find((p) => p.id === point.id).construction, false);
});

for (const type of ["rectangle", "triangle", "circle", "ellipse"]) {
  test(`draft ${type} forms no region, survives import, and undo removes the entire shape`, () => {
    const h = harness();
    h.run("constructionMode = true");
    h.api.createRegularShape({ type, x: 0, y: 0, width: 6, height: 4, radius: 3, angle: 20 });
    assert.equal(h.scene().regions.length, 0);
    assert.ok(h.scene().curves.every((p) => p.construction));
    assert.ok(h.scene().geometryNodes.every((p) => p.construction));
    const restored = h.api.normalizeScene(JSON.parse(JSON.stringify(h.scene())));
    assert.ok(restored.curves.every((p) => p.construction));
    assert.ok(restored.geometryNodes.every((p) => p.construction));
    assert.equal(h.api.collectAnalysisPlacementTopology().curves.length, 0);
    assert.equal(h.api.collectAnalysisPlacementTopology().mandatoryGeometryNodes.length, 0);
    h.api.undoDrawing();
    assert.equal(h.scene().geometryNodes.length + h.scene().curves.length, 0);
  });
}

test("every curve type has draft intersections with a real line", () => {
  for (const type of ["quadratic", "cubic", "arc", "ellipse"]) {
    const h = harness();
    line(h, { x: 0, y: -5 }, { x: 0, y: 5 });
    h.run("constructionMode = true");
    const a = h.api.createGeometryNode({ x: -2, y: 0 });
    const b = h.api.createGeometryNode({ x: 2, y: 0 });
    const controls = type === "cubic" ? [{ x: -1, y: 2 }, { x: 1, y: 2 }] : [{ x: 0, y: 2 }];
    const curve = h.api.createCurve(type, [a.id, b.id], controls);
    assert.ok(h.scene().geometryNodes.some((p) => p.autoGenerated && p.construction && p.intersectionCurveIds.includes(curve.id)), type);
    assert.equal(h.scene().regions.length, 0);
  }
});

test("deleting a draft cleans automatic intersections and undo restores them", () => {
  const h = harness();
  line(h, { x: -5, y: 0 }, { x: 5, y: 0 });
  const curve = line(h, { x: 0, y: -5 }, { x: 0, y: 5 }, true);
  h.api.deleteObject("curve", curve.id);
  assert.ok(!h.scene().geometryNodes.some((p) => p.autoGenerated));
  h.api.undoDrawing();
  assert.equal(h.scene().curves.length, 2);
  assert.ok(h.scene().geometryNodes.some((p) => p.autoGenerated && p.construction));
});

test("a continuous pointer drag is one undo step", () => {
  const h = harness();
  line(h, { x: 0, y: 0 }, { x: 30, y: 0 });
  h.api.onPointerDown({ button: 0, pointerId: 1, x: 0, y: 0 });
  for (let i = 1; i <= 20; i++) h.api.onPointerMove({ x: i, y: i });
  h.api.onPointerUp({ x: 20, y: 20 });
  assert.equal(h.scene().geometryNodes[0].x, 20);
  h.api.undoDrawing();
  assert.equal(h.scene().geometryNodes[0].x, 0);
  assert.equal(h.scene().curves.length, 1);
});

test("curve clicks undo to the preceding construction step including temporary endpoints", () => {
  const h = harness();
  h.run('activeTool = "line"');
  h.api.handleCurveClick("line", { x: 0, y: 0 }, { x: 0, y: 0 });
  h.api.handleCurveClick("line", { x: 30, y: 0 }, { x: 30, y: 0 });
  assert.equal(h.scene().curves.length, 1);
  h.api.undoDrawing();
  assert.equal(h.scene().curves.length, 0);
  assert.equal(h.scene().geometryNodes.length, 1);
  assert.equal(h.run("draft.points.length"), 1);
  h.api.undoDrawing();
  assert.equal(h.scene().geometryNodes.length, 0);
  assert.equal(h.run("draft"), null);
});

test("draft division points and static draft curves stay outside solver classification", () => {
  const h = harness();
  const curve = line(h, { x: 0, y: 0 }, { x: 10, y: 0 }, true);
  const points = h.api.divideSelectedLine(5);
  assert.ok(points.every((p) => p.construction));
  curve.mechanicalState = "static";
  h.scene().geometryNodes.forEach((p) => { p.mechanicalState = "static"; });
  assert.equal(h.api.getGeometryStateAtPoint({ x: 5, y: 0 }).isStatic, false);
  assert.equal(h.api.collectAnalysisPlacementTopology().mandatoryGeometryNodes.length, 0);
});

test("loads on converted geometry are retained but dormant in calculation", () => {
  const h = harness();
  const curve = line(h, { x: 0, y: 0 }, { x: 10, y: 0 });
  h.api.createPointLoad({ x: 0, y: 0 }, { x: 0, y: -1 }, curve.geometryNodeIds[0]);
  h.api.createDistributedLoad(curve.id, { x: 0, y: -1 });
  h.api.selectObject("curve", curve.id);
  h.api.setSelectedConstruction(true);
  const loads = h.api.calculationLoadModel([], new Map(), new Map(), []);
  assert.equal(loads.payload.point.length + loads.payload.distributed.length, 0);
  assert.equal(h.scene().pointLoads.length + h.scene().distributedLoads.length, 2);
  assert.equal(h.api.collectAnalysisPlacementTopology().pointLoadAnchors.length, 0);
  h.api.undoDrawing();
  const restored = h.api.calculationLoadModel([], new Map(), new Map(), []);
  assert.equal(restored.payload.point.length, 1);
  assert.equal(restored.payload.distributed.length, 1);
});

test("clear and JSON import can each be undone as a single command", () => {
  const h = harness();
  line(h, { x: 0, y: 0 }, { x: 10, y: 0 }, true);
  const before = JSON.stringify(h.scene());
  h.api.clearScene();
  assert.equal(h.scene().curves.length, 0);
  h.api.undoDrawing();
  assert.equal(JSON.stringify(h.scene()), before);
  h.api.FileReader = class {
    readAsText(text) { this.result = text; this.onload(); }
  };
  h.api.importScene(JSON.stringify({ name: "Imported", geometryNodes: [{ id: "G1", x: 7, y: 8 }] }));
  assert.equal(h.scene().name, "Imported");
  assert.equal(h.scene().curves.length, 0);
  h.api.undoDrawing();
  assert.equal(JSON.stringify(h.scene()), before);
});

test("a real curve can reuse a draft intersection as a persistent real endpoint", () => {
  const h = harness();
  line(h, { x: -5, y: 0 }, { x: 5, y: 0 }, true);
  line(h, { x: 0, y: -5 }, { x: 0, y: 5 }, true);
  const point = h.scene().geometryNodes.find((p) => p.autoGenerated);
  h.run("constructionMode = false");
  const end = h.api.createGeometryNode({ x: 10, y: 10 });
  h.api.createCurve("line", [point.id, end.id]);
  assert.equal(point.construction, false);
  assert.equal(point.autoGenerated, false);
  h.api.rebuildDerivedRegions();
  assert.equal(point.construction, false);
});
